import { jsx as _jsx, jsxs as _jsxs } from "react/jsx-runtime";
import { useState } from "react";

function DownloadButton({ label, url }) {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const download = async () => {
    setLoading(true);
    setError("");
    try {
      const response = await fetch(url, { credentials: "same-origin" });
      if (!response.ok) {
        const body = await response.json().catch(() => ({}));
        throw new Error(body.message || `Download failed (${response.status}).`);
      }
      const blob = await response.blob();
      const href = URL.createObjectURL(blob);
      const anchor = document.createElement("a");
      anchor.href = href;
      anchor.download = label.toLowerCase().includes("pdf")
        ? "documentation.pdf"
        : "documentation.docx";
      document.body.appendChild(anchor);
      anchor.click();
      anchor.remove();
      window.setTimeout(() => URL.revokeObjectURL(href), 1000);
    } catch (downloadError) {
      setError(downloadError.message || "Unable to download the document.");
    } finally {
      setLoading(false);
    }
  };

  return _jsxs("div", { className: "completed-download-control", children: [
    _jsx("button", {
      type: "button",
      onClick: download,
      disabled: loading,
      children: loading ? "Preparing…" : label,
    }),
    error && _jsx("div", { role: "alert", children: error }),
  ] });
}

export default function Completed({ onNav, state }) {
  const title = state.studentInfo?.projectTitle || state.projectName || "Project Documentation";
  const sections = (state.sections || []).filter((section) => section.enabled);
  const job = state.currentProjectId;

  return _jsxs("div", { className: "completed-page", children: [
    _jsx("div", { className: "completed-success-icon", children: _jsx("svg", {
      width: "36",
      height: "36",
      viewBox: "0 0 24 24",
      fill: "none",
      stroke: "white",
      strokeWidth: "2.5",
      children: _jsx("path", { d: "M20 6L9 17l-5-5" }),
    }) }),
    _jsx("h1", { children: "Documentation Ready!" }),
    _jsxs("p", { children: [title, " has been generated by the backend and is ready for download."] }),
    _jsxs("section", { className: "completed-document-card", children: [
      _jsx("h2", { children: title }),
      _jsxs("div", { className: "completed-section-count", children: [sections.length, " configured sections"] }),
      _jsx(DownloadButton, { label: "Download PDF", url: `/api/documentation/${encodeURIComponent(job)}/download/pdf` }),
      _jsx(DownloadButton, { label: "Download DOCX", url: `/api/documentation/${encodeURIComponent(job)}/download/docx` }),
      _jsx("button", {
        type: "button",
        className: "completed-view-pdf",
        onClick: () => window.open(`/api/documentation/${encodeURIComponent(job)}/view/pdf`, "_blank", "noopener,noreferrer"),
        children: "View PDF",
      }),
    ] }),
    _jsxs("div", { className: "completed-actions", children: [
      _jsx("button", { type: "button", onClick: () => onNav("dashboard"), children: "← Dashboard" }),
      _jsx("button", { type: "button", onClick: () => onNav("add-project"), children: "Generate Another" }),
    ] }),
  ] });
}
